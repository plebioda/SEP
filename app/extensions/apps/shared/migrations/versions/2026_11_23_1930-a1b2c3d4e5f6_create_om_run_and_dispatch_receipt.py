def _create_schema_if_needed() -> str | None:
    """Create OM's schema on a bind that has one, and report what it is called.

    :return: The real schema name, or ``None`` when the bind has no schemas and
        these tables therefore live in the default one.
    """
    schema = om_schema(sep_settings.DATABASE)
    if schema is not None:
        op.execute(sa.schema.CreateSchema(schema, if_not_exists=True))
    return schema


def _qualified(schema: str | None, name: str) -> str:
    """Return a raw-DDL object name, schema-qualified when the bind has a schema.

    :param schema: The resolved schema name, or ``None`` for the default schema.
    :param name: The object's bare name.
    :return: The name a raw ``CREATE FUNCTION`` / ``CREATE TRIGGER`` body uses.
    """
    return f'"{schema}".{name}' if schema is not None else name


def _create_postgres_concurrency(schema: str | None) -> None:
    """Create the epoch guard, the write-once guard and the dispatch function.

    :param schema: The resolved schema the objects and their table references
        live in.
    """
    run = _qualified(schema, "om_run")
    receipt = _qualified(schema, "om_dispatch_receipt")
    catalogue_fn = _qualified(schema, "om_run_catalogue_pinned")
    immutable_fn = _qualified(schema, "om_dispatch_receipt_immutable")
    record_fn = _qualified(schema, "om_record_dispatch")

    op.execute(
        f"CREATE OR REPLACE FUNCTION {catalogue_fn}() RETURNS trigger "
        "LANGUAGE plpgsql AS $$\n"
        "BEGIN\n"
        "  IF NEW.catalogue_version IS DISTINCT FROM OLD.catalogue_version THEN\n"
        "    RAISE EXCEPTION 'om_run.catalogue_version is pinned at create' "
        "USING ERRCODE = 'check_violation';\n"
        "  END IF;\n"
        "  IF NEW.epoch < OLD.epoch THEN\n"
        "    RAISE EXCEPTION 'om_run.epoch cannot decrease' "
        "USING ERRCODE = 'check_violation';\n"
        "  END IF;\n"
        "  RETURN NEW;\n"
        "END $$;"
    )
    op.execute(f"DROP TRIGGER IF EXISTS om_run_catalogue_pinned ON {run};")
    op.execute(
        f"CREATE TRIGGER om_run_catalogue_pinned BEFORE UPDATE ON {run} "
        f"FOR EACH ROW EXECUTE FUNCTION {catalogue_fn}();"
    )

    op.execute(
        f"CREATE OR REPLACE FUNCTION {immutable_fn}() RETURNS trigger "
        "LANGUAGE plpgsql AS $$\n"
        "BEGIN\n"
        "  IF TG_OP = 'DELETE' THEN\n"
        "    RAISE EXCEPTION 'om_dispatch_receipt rows are permanent' "
        "USING ERRCODE = 'check_violation';\n"
        "  END IF;\n"
        "  IF NEW.idempotency_key <> OLD.idempotency_key OR NEW.run_id <> OLD.run_id\n"
        "     OR NEW.epoch <> OLD.epoch OR NEW.executor_token <> OLD.executor_token\n"
        "     OR NEW.descriptor_fingerprint <> OLD.descriptor_fingerprint\n"
        "     OR NEW.node_id <> OLD.node_id THEN\n"
        "    RAISE EXCEPTION 'om_dispatch_receipt identity fields are immutable' "
        "USING ERRCODE = 'check_violation';\n"
        "  END IF;\n"
        "  IF (OLD.accepted_at IS NOT NULL AND NEW.accepted_at IS DISTINCT FROM OLD.accepted_at)\n"
        "     OR (OLD.submission_id IS NOT NULL AND NEW.submission_id IS DISTINCT FROM OLD.submission_id)\n"
        "     OR (OLD.submitted_at IS NOT NULL AND NEW.submitted_at IS DISTINCT FROM OLD.submitted_at)\n"
        "     OR (OLD.completed_at IS NOT NULL AND NEW.completed_at IS DISTINCT FROM OLD.completed_at)\n"
        "     OR (OLD.cancelled_at IS NOT NULL AND NEW.cancelled_at IS DISTINCT FROM OLD.cancelled_at)\n"
        "     OR (OLD.task_history_id IS NOT NULL AND NEW.task_history_id IS DISTINCT FROM OLD.task_history_id)\n"
        "     OR (OLD.result IS NOT NULL AND NEW.result IS DISTINCT FROM OLD.result) THEN\n"
        "    RAISE EXCEPTION 'om_dispatch_receipt transport facts are write-once' "
        "USING ERRCODE = 'check_violation';\n"
        "  END IF;\n"
        "  RETURN NEW;\n"
        "END $$;"
    )
    op.execute(
        f"DROP TRIGGER IF EXISTS om_dispatch_receipt_immutable ON {receipt};"
    )
    op.execute(
        f"CREATE TRIGGER om_dispatch_receipt_immutable "
        f"BEFORE UPDATE OR DELETE ON {receipt} "
        f"FOR EACH ROW EXECUTE FUNCTION {immutable_fn}();"
    )

    op.execute(
        f"CREATE OR REPLACE FUNCTION {record_fn}(run UUID, key TEXT, ep BIGINT, "
        "token TEXT, fingerprint TEXT, node TEXT, OUT receipt_key TEXT, "
        "OUT first_time boolean, OUT executor_token TEXT)\n"
        "LANGUAGE plpgsql AS $$\n"
        f"DECLARE cur BIGINT; existing {receipt};\n"
        "BEGIN\n"
        "  IF token IS NULL OR fingerprint IS NULL OR node IS NULL THEN\n"
        "    RAISE EXCEPTION 'token, fingerprint and node are required' "
        "USING ERRCODE = 'null_value_not_allowed';\n"
        "  END IF;\n"
        f"  SELECT epoch INTO cur FROM {run} WHERE id = run FOR UPDATE;\n"
        "  IF NOT FOUND THEN\n"
        "    RAISE EXCEPTION 'no run %', run USING ERRCODE = 'no_data_found';\n"
        "  END IF;\n"
        "  IF ep < cur THEN\n"
        "    RAISE EXCEPTION 'stale epoch % < % for run %', ep, cur, run "
        "USING ERRCODE = 'serialization_failure';\n"
        "  END IF;\n"
        f"  INSERT INTO {receipt} (idempotency_key, run_id, epoch, executor_token, "
        "descriptor_fingerprint, node_id, created_at)\n"
        "    VALUES (key, run, ep, token, fingerprint, node, now())\n"
        "    ON CONFLICT (idempotency_key) DO NOTHING;\n"
        "  IF FOUND THEN\n"
        "    first_time := true;\n"
        "    executor_token := token;\n"
        "  ELSE\n"
        f"    SELECT * INTO existing FROM {receipt} WHERE idempotency_key = key;\n"
        "    IF existing.run_id <> run THEN\n"
        "      RAISE EXCEPTION 'key % belongs to run %, not %', key, existing.run_id, run "
        "USING ERRCODE = 'unique_violation';\n"
        "    END IF;\n"
        "    IF existing.descriptor_fingerprint IS DISTINCT FROM fingerprint "
        "OR existing.node_id IS DISTINCT FROM node THEN\n"
        "      RAISE EXCEPTION 'descriptor_mismatch for key %', key "
        "USING ERRCODE = 'check_violation';\n"
        "    END IF;\n"
        "    IF existing.cancelled_at IS NOT NULL THEN\n"
        "      RAISE EXCEPTION 'dispatch % was cancelled; not re-submitted', key "
        "USING ERRCODE = 'check_violation';\n"
        "    END IF;\n"
        "    first_time := false;\n"
        "    executor_token := existing.executor_token;\n"
        "  END IF;\n"
        f"  UPDATE {run} SET epoch = ep WHERE id = run AND epoch < ep;\n"
        "  receipt_key := key;\n"
        "END $$;"
    )


def _drop_postgres_concurrency(schema: str | None) -> None:
    """Drop the dispatch function and the two guards created on a PostgreSQL bind.

    :param schema: The resolved schema the objects live in.
    """
    run = _qualified(schema, "om_run")
    receipt = _qualified(schema, "om_dispatch_receipt")
    op.execute(
        f"DROP FUNCTION IF EXISTS {_qualified(schema, 'om_record_dispatch')}"
        "(UUID, TEXT, BIGINT, TEXT, TEXT, TEXT);"
    )
    op.execute(
        f"DROP TRIGGER IF EXISTS om_dispatch_receipt_immutable ON {receipt};"
    )
    op.execute(f"DROP TRIGGER IF EXISTS om_run_catalogue_pinned ON {run};")
    op.execute(
        f"DROP FUNCTION IF EXISTS {_qualified(schema, 'om_dispatch_receipt_immutable')}();"
    )
    op.execute(
        f"DROP FUNCTION IF EXISTS {_qualified(schema, 'om_run_catalogue_pinned')}();"
    )



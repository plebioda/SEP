"""create the om_run and om_dispatch_receipt tables

Revision ID: a1b2c3d4e5f6
Revises:
Create Date: 2026-11-23 19:30:00.000000

The shared Operations run and its dispatch receipts live in OM's ``om`` schema,
a branch of their own like ``om_bootstrap``'s, with no ordering against the other
OM apps' branches. The schema is named symbolically throughout -- translated by
the connection -- except ``CREATE SCHEMA``, which is raw DDL and untranslated.

The dispatch function ``om_record_dispatch`` and the two immutability triggers are
PL/pgSQL and are created only on a PostgreSQL bind; the SQLite test lane gets the
tables but not the concurrency primitives, which the ``@pytest.mark.postgres``
crash matrix exercises on a real engine.

Hand-written, and it has to stay that way: Alembic applies no
``schema_translate_map`` during autogenerate, so ``--autogenerate`` proposes a
literal ``om_schema`` and re-creates these tables on every run. Treat an
autogenerated OM diff as a bug.
"""

